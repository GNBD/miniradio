(function (root, factory) {
  const S = (typeof require === "function") ? require("./schema.js") : root.MRSchema;
  const api = factory(S);
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  if (root) root.MRMenuC = api;
})(typeof globalThis !== "undefined" ? globalThis : this, function (S) {
  const CFG = {
    menu: {
      file: "menu_data.c", arr: "s_menu", items: "g_menu_items",
      count: "g_menu_count", macro: "MENU_LAYOUT_H",
      layoutKey: "menuLayout", defaults: S.MENU_ELEMENTS, pin: "RM_BACK",
    },
    settings: {
      file: "settings_data.c", arr: "s_set", items: "g_set_items",
      count: "g_set_count", macro: "SETTINGS_LAYOUT_H",
      layoutKey: "settingsLayout", defaults: S.SETTINGS_ELEMENTS, pin: "ST_BACK",
    },
  };

  function cstr(s) {
    return JSON.stringify(String(s));
  }

  function listOf(project, which) {
    const cfg = CFG[which];
    const src = Array.isArray(project[which]) && project[which].length
      ? project[which] : cfg.defaults;
    const out = src.map((it) => ({
      id: it.id,
      label: it.label,
      visible: (it.visible === 0 || it.visible === false) ? 0 : 1,
    }));
    const pi = out.findIndex((x) => x.id === cfg.pin);
    if (pi > 0) out.unshift(out.splice(pi, 1)[0]);
    return out;
  }

  function generate(project, which) {
    const cfg = CFG[which];
    if (!cfg) throw new Error("unknown list: " + which);
    const list = listOf(project, which);
    const lines = list.map((it) =>
      "    { " + it.id + ", " + cstr(it.label) + ", " + it.visible + " },");
    const content = [
      "/* Generated by NEWPROJECT Modder Studio - do not edit by hand.",
      " * Drop this file into main/" + cfg.file + " and rebuild. */",
      "#include \"menu_data.h\"",
      "",
      "#define " + cfg.macro + " " +
        ((project[cfg.layoutKey] || "v") === "h" ? 1 : 0),
      "",
      "static const menu_entry_t " + cfg.arr + "[] = {",
      lines.join("\n"),
      "};",
      "",
      "const menu_entry_t *" + cfg.items + " = " + cfg.arr + ";",
      "const int " + cfg.count + " = (int)(sizeof(" + cfg.arr + ") / sizeof(" + cfg.arr + "[0]));",
      "",
    ].join("\n");
    return { name: cfg.file, content };
  }

  return { generate, listOf };
});
